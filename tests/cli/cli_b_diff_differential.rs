fn compose_ws(dir: &std::path::Path) -> CborValue {
    use al_sem::engine::gate::model_instance_id::compute_gate_model_instance_id;
    use al_sem::engine::l5::snapshot_full::{FullSnapshotOptions, compose_full_snapshot};
    use al_sem::program::model::program_calls::assemble_and_resolve_workspace_program;
    let model_id = compute_gate_model_instance_id(dir).expect("modelInstanceId");
    let inputs = al_sem::program::inputs::InputSet::read(
        dir,
        &al_sem::program::inputs::InputNeeds {
            fingerprint_rows: true,
            ..Default::default()
        },
    );
    let resolved =
        assemble_and_resolve_workspace_program(&inputs, &model_id, false).expect("resolve");
    let opts = FullSnapshotOptions {
        inputs: &inputs,
        driver_version: VERSION_OVERRIDE,
        deterministic: true,
        roots_config_ignored: false,
        universe: al_sem::engine::l5::snapshot_full::SnapshotUniverse::SingleApp,
    };
    compose_full_snapshot(&resolved, &opts)
}

#[test]
fn diff_strict_coverage_json_and_exit_byte_match() {
    let old = load_snap("coverage-strict-old.snap.json");
    let new = load_snap("coverage-strict-new.snap.json");

    // Strict json golden.
    let strict = run_engine(&old, &new, CoveragePolicy::Strict);
    let empty: Vec<CborValue> = Vec::new();
    let json = format_diff(&strict, "json", VERSION_OVERRIDE, true, &empty);
    check_or_regen_bytes("coverage-strict.strict.json", &json);

    // Strict exit code = 1 (coverage-incomplete) — driven for real via the CLI
    // orchestrator so the golden text reflects an actually-computed exit code.
    let old_path = snapshots_dir().join("coverage-strict-old.snap.json");
    let new_path = snapshots_dir().join("coverage-strict-new.snap.json");
    let old_s = old_path.to_string_lossy().to_string();
    let new_s = new_path.to_string_lossy().to_string();
    let strict_outcome = run_diff(&DiffCliOptions {
        old_arg: &old_s,
        new_arg: &new_s,
        format: "json",
        out: None,
        coverage_policy: CoveragePolicy::Strict,
        renames_path: None,
        fail_on: None,
        strict: false,
        deterministic: true,
        driver_version: VERSION_OVERRIDE,
    });
    assert_eq!(strict_outcome.exit_code, 1, "strict CLI exit must be 1");
    check_or_regen_bytes(
        "coverage-strict.strict.exitcode.txt",
        &format!("{}\n", strict_outcome.exit_code),
    );
    let strict_failed = strict
        .diagnostics
        .iter()
        .any(|d| d.kind == "coverage-incomplete");
    assert!(
        strict_failed,
        "strict run must produce a coverage-incomplete diagnostic"
    );

    // Loose json + human goldens.
    let loose = run_engine(&old, &new, CoveragePolicy::Loose);
    let loose_json = format_diff(&loose, "json", VERSION_OVERRIDE, true, &empty);
    check_or_regen_bytes("coverage-strict.loose.json", &loose_json);
    let loose_human = format_diff(&loose, "human", VERSION_OVERRIDE, true, &empty);
    check_or_regen_bytes("coverage-strict.loose.human.txt", &loose_human);

    // fail-on medium exit code = 1 — also driven for real via the CLI orchestrator.
    let failon_outcome = run_diff(&DiffCliOptions {
        old_arg: &old_s,
        new_arg: &new_s,
        format: "human",
        out: None,
        coverage_policy: CoveragePolicy::Loose,
        renames_path: None,
        fail_on: Some(Severity::Medium),
        strict: false,
        deterministic: true,
        driver_version: VERSION_OVERRIDE,
    });
    assert_eq!(
        failon_outcome.exit_code, 1,
        "fail-on medium CLI exit must be 1"
    );
    check_or_regen_bytes(
        "coverage-strict.failon.exitcode.txt",
        &format!("{}\n", failon_outcome.exit_code),
    );
    let t = Severity::Medium.rank();
    let triggers = loose.findings.iter().any(|f| f.severity.rank() <= t);
    assert!(
        triggers,
        "fail-on medium must trigger on the loose findings"
    );
}

